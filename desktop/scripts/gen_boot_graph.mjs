#!/usr/bin/env node
/**
 * Generate the boot artifacts for the vendored client:
 *
 * 1. ui/src/boot-graph.generated.ts — the `__CODESMITH_BOOT__` graph (entries
 *    from VENDOR.json plugin rows; inject lists from each package.json's
 *    `codesmith.client.inject`, filtered to rows we vendor).
 * 2. ui/public/plugins/ — static classic-script staging:
 *    - `<id>/<entry>` per plugin row (the graph addresses it with the
 *      `??<id>/<entry>&rev=<rev>` URL form the module system's chunkUrl
 *      parser requires; main.ts's loadBundle maps it back onto this path),
 *    - `<id>/client.*.js` sibling chunks,
 *    - `application.js` — the concatenated application batch, the same shape
 *      the upstream host serves for a batch URL.
 *
 * Run after vendor_client.py. Deterministic for a given vendor tree.
 */
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync, existsSync, rmSync } from 'node:fs'
import { resolve, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = resolve(fileURLToPath(import.meta.url), '..')
const uiDir = join(here, '..', 'ui')
const vendorDir = join(uiDir, 'vendor')
const pluginsDir = join(uiDir, 'public', 'plugins')
const MODULES_ID = '@codesmith/client-modules'

/** Built-in first-party rows prequeued from our own bundle (never fetched). */
const BUILTIN_ROWS = [
  { id: '@codesmith/desktop-brand', entry: 'client.js', inject: [], immediately: false },
  // The coordinator ticket board reads the bridged `agentTeam` projection;
  // it borrows React and the client primitives through the loader table.
  { id: '@codesmith/desktop-ticket-board', entry: 'client.js', inject: [], immediately: false },
  // The subagent catalog reads `subagentCatalog`/`subagentTiming` and opens
  // a child through `uiWorkspace.openSession(address)`.
  { id: '@codesmith/desktop-subagent-catalog', entry: 'client.js', inject: [], immediately: false },
]

/**
 * Vendored packages that stay out of the boot roster. The in-app directory
 * browser is kept for its list/createDirectory primitives and as a future
 * fallback; the composed workspace flow is the native OS chooser, and two
 * occupants of the same directoryFlow holes would open both dialogs.
 */
const SKIP_ROWS = new Set(['@codesmith/client-ui-directory-picker-browse'])

const manifest = JSON.parse(readFileSync(join(vendorDir, 'VENDOR.json'), 'utf8'))
const rev = manifest.source_commit
const rows = []
for (const [name, record] of Object.entries(manifest.packages)) {
  if (!record.plugin || SKIP_ROWS.has(name)) continue
  const pkg = JSON.parse(readFileSync(join(vendorDir, name, 'package.json'), 'utf8'))
  const client = pkg.codesmith?.client
  if (client === undefined) throw new Error(`boot graph: ${name} is a plugin row without a codesmith.client manifest`)
  const inject = (client.inject ?? []).filter(dep => manifest.packages[dep]?.plugin)
  rows.push({
    id: name,
    entry: record.entry,
    inject,
    immediately: client.immediately === true,
  })
}
for (const builtin of BUILTIN_ROWS) {
  if (manifest.packages[builtin.id] !== undefined) throw new Error(`boot graph: built-in row ${builtin.id} collides with a vendored package`)
  rows.push(builtin)
}
const ids = new Set(rows.map(row => row.id))
for (const row of rows) {
  for (const dep of row.inject) {
    if (!ids.has(dep)) throw new Error(`boot graph: ${row.id} injects ${dep} which is not a vendored plugin row`)
  }
}

// --- boot-graph.generated.ts ---
const urlOf = (row) => `plugins/??${row.id}/${row.entry}&rev=${rev}`
const entryTs = rows.map(row => `  { id: ${JSON.stringify(row.id)}, url: ${JSON.stringify(urlOf(row))}, rev: BOOT_REV${row.inject.length ? `, inject: ${JSON.stringify(row.inject)}` : ''}${row.immediately ? ', immediately: true' : ''} },`).join('\n')
const graphTs = `// Generated by desktop/scripts/gen_boot_graph.mjs from ui/vendor — do not edit.
export const BOOT_REV = ${JSON.stringify(rev)}
const MODULES_ID = ${JSON.stringify(MODULES_ID)}
export interface BootEntry { id: string; url: string; rev: string; inject?: string[]; immediately?: boolean }
export const BOOT_ENTRIES: BootEntry[] = [
${entryTs}
]
export function buildBootGraph() {
  const bootstrap = [MODULES_ID]
  const application = BOOT_ENTRIES.filter(row => !bootstrap.includes(row.id)).map(row => row.id)
  return {
    rev: BOOT_REV,
    entries: BOOT_ENTRIES,
    batches: [
      { phase: 'bootstrap', url: BOOT_ENTRIES.find(row => row.id === MODULES_ID)!.url, rev: BOOT_REV, entries: bootstrap },
      { phase: 'application', url: \`plugins/application.js&rev=\${BOOT_REV}\`, rev: BOOT_REV, entries: application },
    ],
  }
}
`
writeFileSync(join(uiDir, 'src', 'boot-graph.generated.ts'), graphTs)

// --- static staging ---
// Files are staged under plain `<id>/` paths: a URL containing `??` cannot
// be served by any static server (the first `?` starts the query string),
// so the `??` URL form lives only in the boot graph (the module system's
// chunkUrl parser needs it) and main.ts's loadBundle hook rewrites it onto
// these plain paths before script injection.
rmSync(pluginsDir, { recursive: true, force: true })
mkdirSync(pluginsDir, { recursive: true })
for (const row of rows) {
  if (BUILTIN_ROWS.some(b => b.id === row.id)) continue
  const lib = join(vendorDir, row.id, 'lib')
  const dir = join(pluginsDir, row.id)
  mkdirSync(dir, { recursive: true })
  copyFileSync(join(lib, row.entry), join(dir, row.entry))
  for (const file of readdirSync(lib)) {
    if (file !== row.entry && /^client\.[\w.-]+\.js$/.test(file)) {
      copyFileSync(join(lib, file), join(dir, file))
    }
  }
}
// Concatenated application batch: each client bundle is a self-contained
// classic script registering itself into __ModuleLoader__. Staged plain;
// the graph's batch URL (`plugins/application.js&rev=…`) is rewritten by the
// loadBundle hook like every other `&rev=` URL.
const application = rows.filter(row => row.id !== MODULES_ID)
const batch = application
  .filter(row => !BUILTIN_ROWS.some(b => b.id === row.id))
  .map(row => readFileSync(join(vendorDir, row.id, 'lib', row.entry), 'utf8')).join('\n;\n')
writeFileSync(join(pluginsDir, 'application.js'), batch)

const modulesEntry = rows.find(row => row.id === MODULES_ID)?.entry
if (!modulesEntry || !existsSync(join(pluginsDir, MODULES_ID, modulesEntry))) {
  throw new Error(`boot graph: ${MODULES_ID} client bundle missing from staging`)
}

// Keep the blocking bootstrap <script src> in index.html on the staged path.
const indexPath = join(uiDir, 'index.html')
let index = readFileSync(indexPath, 'utf8')
const updated = index.replace(
  /<script src="plugins\/[^"]*client\.js[^"]*"><\/script>/,
  `<script src="plugins/${MODULES_ID}/${modulesEntry}"></script>`,
)
if (updated === index && !index.includes(`plugins/${MODULES_ID}/${modulesEntry}"`)) {
  throw new Error('boot graph: index.html bootstrap script tag not found for rewrite')
}
if (updated !== index) writeFileSync(indexPath, updated)
console.log(`boot graph: ${rows.length} rows, rev ${rev.slice(0, 12)}, staged ${application.length} application bundles + ${MODULES_ID}`)
