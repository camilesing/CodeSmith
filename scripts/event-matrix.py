#!/usr/bin/env python3
"""Extension event matrix generator (round-9 TODO-61).

Every `ExtensionEventKind` with its declared dispatch mode (the exhaustive
`dispatch_mode()` match in crates/agent/src/extension.rs), the source files
that emit it, and the in-tree Rust subscribers — regenerated into
docs/EVENT_MATRIX.md so "who fires this, who listens" is a generated fact,
not a code search. `--check` compares with the committed document and exits
non-zero on drift (CI gate — regenerate with
`python3 scripts/event-matrix.py`).

Heuristics (deliberately simple, like capability-graph.py):
- producers   = non-test code constructing `ExtensionEvent::<Variant>` —
                a bare-identifier payload (`ExtensionEvent::X(e)`), a
                `matches!` argument, or a variant followed by `=>` / `|`
                is a pattern, not a construction
- subscribers = `on_variant(ExtensionEventKind::X` / `on_variant_scoped(...`
- test code   = everything from a file's first column-0 `#[cfg(test)]`
                followed by `mod`, `tests.rs` / `test_support` files,
                `tests/` paths, and test-only fixture crates
- a `Transform(ExtensionEvent::X ..)` is a handler's rewritten event and a
  borrowed `&ExtensionEvent::X(..)` a conversion input; dispatch takes the
  event by value, so neither is counted
Producer cells list files with their construction count — no line numbers,
so ordinary edits do not churn the document.

Known limitation: the UI `Event`, `HookEvent`, and protocol `EventFrame`
vocabularies are not covered; script mods (`on_event`) live outside the
tree and are not scanned.
"""

import argparse
import importlib.util
import re
import sys
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_PATH = REPO_ROOT / "docs" / "EVENT_MATRIX.md"
EXTENSION_RS = REPO_ROOT / "crates" / "agent" / "src" / "extension.rs"
# Workspace crates that only exist to test others (never a producer).
TEST_ONLY_CRATES = {"extensions-fixture-dylib"}


def _load_capability_graph():
    spec = importlib.util.spec_from_file_location(
        "capability_graph", REPO_ROOT / "scripts" / "capability-graph.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


strip_rust_comments = _load_capability_graph().strip_rust_comments

HEADER = """\
# Extension Event Matrix (generated)

> Generated by `scripts/event-matrix.py` — do not hand-edit.
> Regenerate with `python3 scripts/event-matrix.py`; CI verifies
> freshness with `--check`.

Each `ExtensionEventKind` with its declared dispatch mode (`dispatch_mode()`
in `crates/agent/src/extension.rs` — see the dispatch three-states in
`docs/EXTENSIONS.md`), the source files that construct it for dispatch
(count per file), and the in-tree Rust subscribers (`on_variant` /
`on_variant_scoped`). `—` marks an empty column: a kind with no producer is
a gap worth explaining; most kinds have no in-tree subscriber because
extensions and mods subscribe from outside the tree.

Known limitation: the UI `Event`, `HookEvent`, and protocol `EventFrame`
vocabularies are not covered.

| Event | Dispatch | Producers | In-tree subscribers |
|---|---|---|---|
"""


def dispatch_modes() -> dict[str, str]:
    text = strip_rust_comments(EXTENSION_RS.read_text(encoding="utf-8"))
    start = text.index("pub fn dispatch_mode(self) -> DispatchMode")
    body = text[start : text.index("\n    }\n", start)]
    modes: dict[str, str] = {}
    arm = re.compile(
        r"((?:ExtensionEventKind::\w+\s*\|?\s*)+)=>\s*\{?\s*DispatchMode::(\w+)"
        r"(?:\s*\{\s*can_deny:\s*(true|false)\s*\})?"
    )
    for match in arm.finditer(body):
        mode = match.group(2)
        if match.group(3) is not None:
            mode = f"Waterfall (can_deny: {match.group(3)})"
        for kind in re.findall(r"ExtensionEventKind::(\w+)", match.group(1)):
            modes[kind] = mode
    if not modes:
        sys.exit("event-matrix: could not parse dispatch_mode() in extension.rs")
    return modes


def production_text(path: Path) -> str:
    text = strip_rust_comments(path.read_text(encoding="utf-8", errors="replace"))
    cut = re.search(r"^#\[cfg\(test\)\]\s*\n\s*mod ", text, re.MULTILINE)
    return text[: cut.start()] if cut else text


def closing(text: str, open_at: int, open_ch: str, close_ch: str) -> int:
    depth = 0
    for index in range(open_at, len(text)):
        if text[index] == open_ch:
            depth += 1
        elif text[index] == close_ch:
            depth -= 1
            if depth == 0:
                return index
    return len(text) - 1


def constructions(text: str) -> list[str]:
    found = []
    for match in re.finditer(r"\bExtensionEvent::(\w+)", text):
        variant, end = match.group(1), match.end()
        before = text[max(0, match.start() - 60) : match.start()]
        if (
            "matches!(" in before
            or before.rstrip().endswith("Transform(")
            or before.rstrip().endswith("&")
        ):
            continue
        after = end
        if end < len(text) and text[end] == "(":
            close = closing(text, end, "(", ")")
            if re.fullmatch(r"\s*(_|\.\.|[a-z_][a-z0-9_]*)\s*", text[end + 1 : close]):
                continue
            after = close + 1
        elif re.match(r"\s*\{", text[end:]):
            brace = text.index("{", end)
            after = closing(text, brace, "{", "}") + 1
        tail = text[after : after + 8].lstrip()
        if tail.startswith("=>") or tail.startswith("|") or tail.startswith("="):
            continue
        found.append(variant)
    return found


def scan(kinds: list[str]):
    producers: dict[str, Counter] = {kind: Counter() for kind in kinds}
    subscribers: dict[str, Counter] = {kind: Counter() for kind in kinds}
    for path in sorted((REPO_ROOT / "crates").glob("*/src/**/*.rs")):
        parts = path.relative_to(REPO_ROOT).parts
        if "target" in parts or "tests" in parts or "test_support" in path.as_posix():
            continue
        if path == EXTENSION_RS or path.name in ("test_support.rs", "tests.rs"):
            continue
        if parts[1] in TEST_ONLY_CRATES:
            continue
        text = production_text(path)
        label = "/".join((parts[1].removeprefix("codesmith-"),) + parts[3:])
        for variant in constructions(text):
            if variant in producers:
                producers[variant][label] += 1
        for variant in re.findall(
            r"on_variant(?:_scoped)?\s*\(\s*ExtensionEventKind::(\w+)", text
        ):
            if variant in subscribers:
                subscribers[variant][label] += 1
    return producers, subscribers


def cell(counter: Counter) -> str:
    if not counter:
        return "—"
    return ", ".join(
        f"`{name}`" + (f" ×{count}" if count > 1 else "")
        for name, count in sorted(counter.items())
    )


def render() -> str:
    modes = dispatch_modes()
    kinds = sorted(modes)
    producers, subscribers = scan(kinds)
    rows = [
        f"| `{kind}` | {modes[kind]} | {cell(producers[kind])} | {cell(subscribers[kind])} |\n"
        for kind in kinds
    ]
    return HEADER + "".join(rows)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the committed matrix is stale")
    args = parser.parse_args()
    rendered = render()
    if args.check:
        current = OUT_PATH.read_text(encoding="utf-8") if OUT_PATH.exists() else ""
        if current != rendered:
            print(
                "docs/EVENT_MATRIX.md is stale — regenerate with "
                "`python3 scripts/event-matrix.py`",
                file=sys.stderr,
            )
            return 1
        print(f"event matrix fresh ({rendered.count(chr(10) + '| `')} events)")
        return 0
    OUT_PATH.write_text(rendered, encoding="utf-8")
    print(f"wrote docs/EVENT_MATRIX.md ({rendered.count(chr(10) + '| `')} events)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
